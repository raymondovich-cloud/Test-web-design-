// source/application/training/save-training-session.js — Version 1.2
// Responsibility: create a session and insert it without overwriting an existing record.
import {createTrainingSession} from "../../domain/training/training-session.js";
import {createTrainingSessionPersistenceResult} from "./training-session-persistence-result.js";

function createSaveTrainingSession({repository,clock,createId}={}){
 if(!repository||typeof repository.insertForUser!=="function")throw new TypeError("Save training session: repository.insertForUser is required.");
 if(typeof clock!=="function"||typeof createId!=="function")throw new TypeError("Save training session: clock and createId dependencies are required.");
 async function execute({userContext,session}={}){
  const userId=userContext?.userId;
  if(typeof userId!=="string"||!userId.trim())throw new TypeError("Save training session: authenticated user context is required.");
  if(!session||typeof session!=="object"||Array.isArray(session))throw new TypeError("Save training session: session input is required.");
  const now=clock();if(!Number.isFinite(now)||now<0)throw new TypeError("Save training session: clock must return a valid timestamp.");
  const id=createId();if(typeof id!=="string"||!id.trim())throw new TypeError("Save training session: createId must return a non-empty UUID.");
  // Creation timestamps and identity are generated by Application, never trusted from client input.
  const entity=createTrainingSession({...session,id,createdAt:now,startedAt:null,updatedAt:now});
  const stored=await repository.insertForUser(userId.trim(),entity);
  const result=createTrainingSessionPersistenceResult(stored,entity.id);
  if(result.revision!==1)throw new Error("Save training session: repository must start a new session at revision 1.");
  return result;
 }
 return Object.freeze({execute});
}
export {createSaveTrainingSession};
